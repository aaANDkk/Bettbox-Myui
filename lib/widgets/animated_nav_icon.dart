final Expando<Rect> _pathBoundsCache = Expando<Rect>();

Rect _boundsOf(Path path) => _pathBoundsCache[path] ??= path.getBounds();

class FluentSvgPainter extends CustomPainter {
  final Path regularPath;
  final Path filledPath;
  final double progress;
  final Color color;

  FluentSvgPainter({
    required this.regularPath,
    required this.filledPath,
    required this.progress,
    required this.color,
  });

  @override
  void paint(Canvas canvas, Size size) {
    canvas.save();
    canvas.scale(size.width / 24.0, size.height / 24.0);

    // 各图标墨迹范围不同（主页 18×19，更多 20×20），统一按包围盒归一 + 居中，
    // 否则底栏每个图标看起来大小与居中程度不一致
    final Rect bounds = _boundsOf(regularPath);
    final double maxDim = math.max(bounds.width, bounds.height);
    if (maxDim > 0) {
      final double scale = _opticalSize / maxDim;
      canvas.translate(12.0, 12.0);
      canvas.scale(scale, scale);
      canvas.translate(-bounds.center.dx, -bounds.center.dy);
    }

    final paint = Paint()
      ..color = color
      ..style = PaintingStyle.fill;

    if (progress <= 0.0) {
      canvas.drawPath(regularPath, paint);
      canvas.restore();
      return;
    }

    if (progress >= 1.0) {
      canvas.drawPath(filledPath, paint);
      canvas.restore();
      return;
    }

    final center = const Offset(12.0, 12.0);
    const maxRadius = 17.5;
    final currentRadius = maxRadius * progress;

    final regScale = math.max(0.001, 1.0 - 0.10 * progress);
    final regAlpha = ((1.0 - progress * 1.3).clamp(0.0, 1.0) * color.a).clamp(
      0.0,
      1.0,
    );
    if (regAlpha > 0) {
      canvas.save();
      canvas.translate(center.dx, center.dy);
      canvas.scale(regScale);
      canvas.translate(-center.dx, -center.dy);
      canvas.drawPath(
        regularPath,
        Paint()..color = color.withValues(alpha: regAlpha),
      );
      canvas.restore();
    }

    canvas.save();
    final clipPath = Path()
      ..addOval(Rect.fromCircle(center: center, radius: currentRadius));
    canvas.clipPath(clipPath);

    final fillScale = 0.90 + 0.10 * progress;
    canvas.translate(center.dx, center.dy);
    canvas.scale(fillScale);
    canvas.translate(-center.dx, -center.dy);
    canvas.drawPath(filledPath, paint);
    canvas.restore();

    canvas.restore();
  }

  @override
  bool shouldRepaint(FluentSvgPainter oldDelegate) =>
      progress != oldDelegate.progress ||
      color != oldDelegate.color ||
      regularPath != oldDelegate.regularPath ||
      filledPath != oldDelegate.filledPath;
}

class AnimatedNavIcon extends StatefulWidget {
  final PageLabel label;
  final bool selected;
  final Color? color;
  final double size;

  const AnimatedNavIcon({
    super.key,
    required this.label,
    required this.selected,
    this.color,
    this.size = 24.0,
  });

  @override
  State<AnimatedNavIcon> createState() => _AnimatedNavIconState();
}

class _AnimatedNavIconState extends State<AnimatedNavIcon>
    with TickerProviderStateMixin {
  late final AnimationController _fillController = AnimationController(
    vsync: this,
    duration: const Duration(milliseconds: 320),
    value: widget.selected ? 1.0 : 0.0,
  );
  late final CurvedAnimation _fill = CurvedAnimation(
    parent: _fillController,
    curve: Curves.easeInOutCubic,
  );
  late final AnimationController _popController = AnimationController(
    vsync: this,
    duration: const Duration(milliseconds: 320),
  );
  late final Listenable _animation = Listenable.merge([_fill, _popController]);

  @override
  void didUpdateWidget(covariant AnimatedNavIcon oldWidget) {
    super.didUpdateWidget(oldWidget);
    if (oldWidget.selected == widget.selected) return;
    if (widget.selected) {
      _fillController.forward();
      if (!_popController.isAnimating) {
        _popController.forward(from: 0.0);
      }
    } else {
      _fillController.reverse();
    }
  }

  @override
  void dispose() {
    _fill.dispose();
    _fillController.dispose();
    _popController.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return AnimatedBuilder(
      animation: _animation,
      builder: (context, _) {
        final fillProgress = _fill.value;
        final pop = _popController.isAnimating
            ? math.sin(math.pi * _popController.value) * 0.12
            : 0.0;
        final targetColor =
            widget.color ?? IconTheme.of(context).color ?? Colors.black;
        final svgPair = widget.label.fluentSvg;

        return Transform.scale(
          scale: 1.0 + pop,
          child: SizedBox.square(
            dimension: widget.size,
            child: CustomPaint(
              size: Size.square(widget.size),
              painter: FluentSvgPainter(
                regularPath: svgPair.regularPath,
                filledPath: svgPair.filledPath,
                progress: fillProgress,
                color: targetColor,
              ),
            ),
          ),
        );
      },
    );
  }
}
